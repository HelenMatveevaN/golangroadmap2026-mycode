package main

import (
	"fmt"
	"reflect"
)

func main() {
	var x float64 = 3.4
	fmt.Println("Оригинал до изменения:", x) // 3.4

	// Шаг 1: Передаем УКАЗАТЕЛЬ на переменную (&x)
	// Теперь ValueOf хранит адрес памяти, где лежит оригинальный x
	p := reflect.ValueOf(&x)
	fmt.Println("Тип p:", p.Type()) // *float64

	// Шаг 2: Вызываем .Elem()
	// Это говорит рефлексии: "перейди по указателю к самим данным"
	v := p.Elem()
	fmt.Println("Тип v после .Elem():", v.Type()) // float64

	// Шаг 3: Проверяем, можно ли менять значение
	if v.CanSet() {
		// Изменяем оригинальную переменную напрямую в памяти
		v.SetFloat(7.1)
	}

	fmt.Println("Оригинал после изменения:", x) // 7.1 (значение изменилось!)
}
